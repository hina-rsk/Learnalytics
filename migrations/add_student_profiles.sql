-- Create student_profiles table to enhance student information
CREATE TABLE IF NOT EXISTS student_profiles (
    id INT AUTO_INCREMENT PRIMARY KEY,
    student_id INT NOT NULL UNIQUE,
    student_id_number VARCHAR(50) UNIQUE NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    middle_initial VARCHAR(5),
    date_of_birth DATE,
    gender VARCHAR(50),
    email VARCHAR(255) NOT NULL,
    contact_number VARCHAR(20) NOT NULL,
    program_id INT,
    department_id INT,
    section_id INT,
    advisor_id INT,
    year_level ENUM('1st Year', '2nd Year', '3rd Year', '4th Year', 'Other') DEFAULT '1st Year',
    enrollment_status ENUM('Active', 'Inactive', 'Graduated', 'Suspended', 'Dropped') DEFAULT 'Active',
    bio TEXT,
    profile_picture VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (program_id) REFERENCES programs(id) ON DELETE SET NULL,
    FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
    FOREIGN KEY (section_id) REFERENCES sections(id) ON DELETE SET NULL,
    FOREIGN KEY (advisor_id) REFERENCES users(id) ON DELETE SET NULL,
    INDEX idx_student_search (student_id_number, year_level, enrollment_status),
    INDEX idx_program_department (program_id, department_id)
);
